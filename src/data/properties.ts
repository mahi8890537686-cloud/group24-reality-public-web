export const featuredProperties = properties.filter((p) => p.isFeatured);

export function getPropertyBySlug(slug: string): Property | undefined {
  return properties.find((p) => p.slug === slug);
}

export function getPropertiesByLocation(location: string): Property[] {
  return properties.filter((p) => p.location === location);
}

export function getRelatedProperties(
  current: Property,
  limit = 3
): Property[] {
  return properties
    .filter((p) => p.id !== current.id && p.location === current.location)
    .slice(0, limit);
}
